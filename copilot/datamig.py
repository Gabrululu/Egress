POSTGRES_SH = r'''#!/usr/bin/env bash
# Egress data migration 1/3: Amazon RDS (PostgreSQL) -> PostgreSQL in the migrated stack.
# pg_dump/pg_restore run in pinned containers: no local PostgreSQL client needed.
# DRY RUN by default. Execute with:  CONFIRM=yes SOURCE_PASSWORD=... ./01_postgres.sh
''' + _COMMON + r'''
PG_IMAGE="@PG_IMAGE@"
SOURCE_HOST="${SOURCE_HOST:-${RDS_ENDPOINT:-}}"   # e.g. @DB_ID@.xxxx.@REGION@.rds.amazonaws.com
SOURCE_PORT="${SOURCE_PORT:-5432}"
SOURCE_DB="${SOURCE_DB:-@DB_NAME@}"
SOURCE_USER="${SOURCE_USER:-@DB_USER@}"
SOURCE_SSLMODE="${SOURCE_SSLMODE:-require}"
TARGET_HOST="${TARGET_HOST:-localhost}"
TARGET_PORT="${TARGET_PORT:-5432}"
TARGET_DB="${TARGET_DB:-uploads}"
TARGET_USER="${TARGET_USER:-app}"
TARGET_PASSWORD="${TARGET_PASSWORD:-${DB_PASSWORD:-}}"
require SOURCE_HOST SOURCE_PASSWORD TARGET_PASSWORD

echo "RDS  ${SOURCE_USER}@${SOURCE_HOST}:${SOURCE_PORT}/${SOURCE_DB}  ->  ${TARGET_USER}@${TARGET_HOST}:${TARGET_PORT}/${TARGET_DB}"
if [ "${CONFIRM:-no}" != "yes" ]; then
  echo "[dry-run] would stream: pg_dump --format=custom --no-owner --no-privileges | pg_restore --clean --if-exists --exit-on-error"
  echo "[dry-run] target tables with the same names will be REPLACED. Re-run with CONFIRM=yes to execute."
  exit 0
fi

src() { docker run --rm -i --network host -e PGPASSWORD="$SOURCE_PASSWORD" -e PGSSLMODE="$SOURCE_SSLMODE" "$PG_IMAGE" "$@"; }
dst() { docker run --rm -i --network host -e PGPASSWORD="$TARGET_PASSWORD" "$PG_IMAGE" "$@"; }
SRC_ARGS=(-h "$SOURCE_HOST" -p "$SOURCE_PORT" -U "$SOURCE_USER" -d "$SOURCE_DB")
DST_ARGS=(-h "$TARGET_HOST" -p "$TARGET_PORT" -U "$TARGET_USER" -d "$TARGET_DB")

src pg_dump --format=custom --no-owner --no-privileges "${SRC_ARGS[@]}" \
  | dst pg_restore --no-owner --no-privileges --clean --if-exists --exit-on-error "${DST_ARGS[@]}"

echo "Verifying row counts (source vs target):"
TABLES_SQL="SELECT quote_ident(table_schema)||'.'||quote_ident(table_name) FROM information_schema.tables WHERE table_type='BASE TABLE' AND table_schema NOT IN ('pg_catalog','information_schema') ORDER BY 1"
status=0
for t in $(src psql -At "${SRC_ARGS[@]}" -c "$TABLES_SQL"); do
  a=$(src psql -At "${SRC_ARGS[@]}" -c "SELECT count(*) FROM $t")
  b=$(dst psql -At "${DST_ARGS[@]}" -c "SELECT count(*) FROM $t")
  if [ "$a" = "$b" ]; then echo "  OK   $t  $a rows"; else echo "  DIFF $t  source=$a target=$b"; status=1; fi
done
exit $status
'''

S3_SH = r'''#!/usr/bin/env bash
# Egress data migration 2/3: Amazon S3 bucket -> SeaweedFS (S3-compatible) with rclone.
# rclone runs in a pinned container: no local install needed.
# DRY RUN by default (rclone --dry-run). Execute with:  CONFIRM=yes ./02_s3.sh
''' + _COMMON + r'''
RCLONE_IMAGE="@RCLONE_IMAGE@"
SOURCE_BUCKET="${SOURCE_BUCKET:-@BUCKET@}"
SOURCE_PROVIDER="${SOURCE_PROVIDER:-AWS}"        # set SOURCE_S3_ENDPOINT for non-AWS sources
SOURCE_REGION="${SOURCE_REGION:-${AWS_REGION:-@REGION@}}"
SOURCE_S3_ENDPOINT="${SOURCE_S3_ENDPOINT:-}"
SOURCE_ACCESS_KEY="${SOURCE_ACCESS_KEY:-${AWS_ACCESS_KEY_ID:-}}"
SOURCE_SECRET_KEY="${SOURCE_SECRET_KEY:-${AWS_SECRET_ACCESS_KEY:-}}"
TARGET_BUCKET="${TARGET_BUCKET:-$SOURCE_BUCKET}"
TARGET_S3_ENDPOINT="${TARGET_S3_ENDPOINT:-http://localhost:9000}"
TARGET_ACCESS_KEY="${TARGET_ACCESS_KEY:-egress}"
TARGET_SECRET_KEY="${TARGET_SECRET_KEY:-${S3_SECRET_KEY:-}}"
require SOURCE_BUCKET SOURCE_ACCESS_KEY SOURCE_SECRET_KEY TARGET_SECRET_KEY

rclone() {
  docker run --rm --network host \
    -e RCLONE_CONFIG_SRC_TYPE=s3 -e RCLONE_CONFIG_SRC_PROVIDER="$SOURCE_PROVIDER" \
    -e RCLONE_CONFIG_SRC_ACCESS_KEY_ID="$SOURCE_ACCESS_KEY" -e RCLONE_CONFIG_SRC_SECRET_ACCESS_KEY="$SOURCE_SECRET_KEY" \
    -e RCLONE_CONFIG_SRC_REGION="$SOURCE_REGION" -e RCLONE_CONFIG_SRC_ENDPOINT="$SOURCE_S3_ENDPOINT" \
    -e RCLONE_CONFIG_DST_TYPE=s3 -e RCLONE_CONFIG_DST_PROVIDER=SeaweedFS \
    -e RCLONE_CONFIG_DST_ACCESS_KEY_ID="$TARGET_ACCESS_KEY" -e RCLONE_CONFIG_DST_SECRET_ACCESS_KEY="$TARGET_SECRET_KEY" \
    -e RCLONE_CONFIG_DST_ENDPOINT="$TARGET_S3_ENDPOINT" -e RCLONE_CONFIG_DST_FORCE_PATH_STYLE=true \
    "$RCLONE_IMAGE" "$@"
}

echo "s3://${SOURCE_BUCKET} (${SOURCE_PROVIDER}${SOURCE_S3_ENDPOINT:+ @ $SOURCE_S3_ENDPOINT})  ->  ${TARGET_S3_ENDPOINT}/${TARGET_BUCKET}"
DRY=(--dry-run)
if [ "${CONFIRM:-no}" = "yes" ]; then DRY=(); rclone mkdir "dst:${TARGET_BUCKET}"; else echo "[dry-run] nothing will be written; CONFIRM=yes to execute"; fi
rclone sync "src:${SOURCE_BUCKET}" "dst:${TARGET_BUCKET}" --checksum --stats-one-line --stats 5s -v "${DRY[@]}"
if [ "${CONFIRM:-no}" = "yes" ]; then
  echo "Verifying (rclone check, one-way):"
  rclone check "src:${SOURCE_BUCKET}" "dst:${TARGET_BUCKET}" --one-way
fi
'''

SQS_PY = r'''#!/usr/bin/env python3
"""Egress data migration 3/3: drain an Amazon SQS queue into RabbitMQ.

At-least-once: each message is published to RabbitMQ with publisher confirms and only then
deleted from SQS. Consumers must be idempotent (the migrated worker is).
DRY RUN by default (peeks one batch, deletes nothing). Execute with --execute.

Requires: pip install boto3 pika   (both are in the migrated app's requirements)
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path


def load_env(path: Path) -> None:
    if path.is_file():
        for line in path.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, _, v = line.partition("=")
                os.environ.setdefault(k.strip(), v.strip())


def drain(sqs, queue_url: str, publish, execute: bool, max_messages: int | None = None,
          wait_seconds: int = 2) -> dict:
    """Move messages from SQS via `publish(body: bytes)` (must raise on failure)."""
    seen = moved = failed = 0
    while True:
        resp = sqs.receive_message(QueueUrl=queue_url, MaxNumberOfMessages=10, WaitTimeSeconds=wait_seconds,
                                   VisibilityTimeout=60 if execute else 0, AttributeNames=["All"])
        msgs = resp.get("Messages", [])
        if not msgs:
            break
        for m in msgs:
            seen += 1
            if not execute:
                continue
            try:
                publish(m["Body"].encode("utf-8"))
            except Exception as e:  # not confirmed: leave it in SQS (visible again after timeout)
                failed += 1
                print(f"publish failed, message kept in SQS: {e}", file=sys.stderr)
                continue
            sqs.delete_message(QueueUrl=queue_url, ReceiptHandle=m["ReceiptHandle"])
            moved += 1
            if max_messages and moved >= max_messages:
                return {"seen": seen, "moved": moved, "failed": failed}
        if not execute:
            break  # dry run: one batch is enough to show what would move
    return {"seen": seen, "moved": moved, "failed": failed}


def main(argv=None) -> int:
    load_env(Path(__file__).resolve().parent.parent / ".env")
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--queue-url", default=os.environ.get("SQS_QUEUE_URL", "@QUEUE_URL@"))
    ap.add_argument("--region", default=os.environ.get("AWS_REGION", "@REGION@"))
    ap.add_argument("--amqp-url", default=os.environ.get(
        "AMQP_URL", f"amqp://egress:{os.environ.get('RABBITMQ_PASSWORD', '')}@localhost:5672/%2F"))
    ap.add_argument("--queue-name", default=os.environ.get("QUEUE_NAME", "@QUEUE@"))
    ap.add_argument("--max", type=int, default=None, help="stop after moving N messages")
    ap.add_argument("--execute", action="store_true", help="really move messages (default: dry run)")
    args = ap.parse_args(argv)
    if not args.queue_url:
        print("error: set SQS_QUEUE_URL or --queue-url", file=sys.stderr)
        return 2

    import boto3
    import pika

    sqs = boto3.client("sqs", region_name=args.region)
    conn = pika.BlockingConnection(pika.URLParameters(args.amqp_url))
    ch = conn.channel()
    ch.queue_declare(queue=args.queue_name, durable=True)
    ch.confirm_delivery()  # basic_publish raises if RabbitMQ does not confirm

    def publish(body: bytes) -> None:
        ch.basic_publish(exchange="", routing_key=args.queue_name, body=body, mandatory=True,
                         properties=pika.BasicProperties(delivery_mode=2))

    print(f"{args.queue_url}  ->  rabbitmq:{args.queue_name}  ({'EXECUTE' if args.execute else 'dry run'})")
    stats = drain(sqs, args.queue_url, publish, args.execute, args.max)
    conn.close()
    print(stats)
    return 1 if stats["failed"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

DYNAMO_MD = """# DynamoDB -> PostgreSQL JSONB (manual step)

DynamoDB items cannot be copied blindly: the access patterns (partition/sort keys, GSIs,
conditional writes) must be redesigned. Suggested path:

1. Export the table: `aws dynamodb export-table-to-point-in-time` (to S3, DynamoDB JSON).
2. Create a table in Postgres: `CREATE TABLE items (pk text, sk text, doc jsonb, PRIMARY KEY (pk, sk));`
   plus indexes for each GSI (`CREATE INDEX ON items ((doc->>'attr'));`).
3. Convert the export to JSONL and load it with `COPY items (pk, sk, doc) FROM STDIN`.
4. Replace `get_item`/`query` calls with SQL; keep the old table read-only until verified.
"""


def _readme(scripts: list[str], res: dict) -> str:
    steps = {
        "01_postgres.sh": "RDS → PostgreSQL: `SOURCE_PASSWORD=... ./01_postgres.sh` (dry run), then `CONFIRM=yes ...`. "
                          "Verifies row counts per table.",
        "02_s3.sh": "S3 → SeaweedFS: `AWS_ACCESS_KEY_ID=... AWS_SECRET_ACCESS_KEY=... ./02_s3.sh` (rclone --dry-run), "
                    "then `CONFIRM=yes ...`. Verifies with `rclone check`.",
        "03_sqs_to_rabbitmq.py": "SQS → RabbitMQ: `python3 03_sqs_to_rabbitmq.py` (peek), then `--execute`. "
                                 "Run it last, after writers are switched over.",
        "04_dynamodb.md": "DynamoDB: data-model change, see the guide.",
    }
    detected = ", ".join(f"{k}={v}" for k, v in res.items() if v) or "none"
    lines = ["# Data migration (generated by Egress)", "",
             "Moves the **data** from AWS to the migrated stack. All scripts are **dry runs unless "
             "confirmed** and read the stack credentials from `../.env`. Only Docker is required "
             "(plus `boto3`/`pika` for the SQS drain).", "",
             f"Defaults inferred from your repo: {detected}. Override any value with environment variables.", "",
             "## Cut-over order", "",
             "1. Deploy the migrated stack (`docker compose up -d` in `output/`).",
             "2. Freeze writes on AWS (maintenance mode / scale writers to 0).", ""]
    for i, s in enumerate(scripts, start=3):
        lines.append(f"{i}. {steps[s]}")
    lines += [f"{len(scripts) + 3}. Point traffic (DNS / clients) to the new stack, then unfreeze.",
              f"{len(scripts) + 4}. Keep AWS read-only for a rollback window, then `terraform destroy`.", "",
              "## Rollback", "", "Nothing on AWS is modified except SQS messages that were successfully "
              "delivered to RabbitMQ. Until DNS is switched, rolling back means just unfreezing AWS.", ""]
    return "\n".join(lines)


def generate_data_migration(target: Path, scan_report: dict, out: Path) -> dict:
    """Write output/data-migration/ for the detected services. Returns metadata."""
    services = set(scan_report.get("services", {}))
    res = infer_resources(Path(target))
    region = res["region"] or "eu-west-1"
    subs = {"@PG_IMAGE@": PG_IMAGE, "@RCLONE_IMAGE@": RCLONE_IMAGE, "@BUCKET@": res["bucket"] or "",
            "@QUEUE@": res["queue"] or "egress-demo-jobs", "@QUEUE_URL@": res["queue_url"] or "",
            "@DB_NAME@": res["db_name"] or "postgres", "@DB_USER@": res["db_user"] or "postgres",
            "@DB_ID@": res["db_identifier"] or "my-db", "@REGION@": region}

    def render(tmpl: str) -> str:
        for k, v in subs.items():
            tmpl = tmpl.replace(k, v)
        return tmpl

    d = Path(out) / DIR_NAME
    d.mkdir(parents=True, exist_ok=True)
    plan = [("RDS", "01_postgres.sh", POSTGRES_SH), ("S3", "02_s3.sh", S3_SH),
            ("SQS", "03_sqs_to_rabbitmq.py", SQS_PY), ("DynamoDB", "04_dynamodb.md", DYNAMO_MD)]
    scripts = []
    for svc, name, tmpl in plan:
        if svc in services:
            path = d / name
            path.write_text(render(tmpl), encoding="utf-8")
            if name.endswith((".sh", ".py")):
                path.chmod(0o755)
            scripts.append(name)
    (d / "README.md").write_text(_readme(scripts, res), encoding="utf-8")
    return {"dir": str(d), "scripts": scripts, "resources": res}
