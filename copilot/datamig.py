"""Data migration scripts: move the *data* (not just the code) from AWS to the migrated stack.

Generated into output/data-migration/ for the services the scan found:
  01_postgres.sh          RDS (PostgreSQL)  -> PostgreSQL   (pg_dump | pg_restore, in containers)
  02_s3.sh                S3 bucket         -> SeaweedFS    (rclone sync + check, in a container)
  03_sqs_to_rabbitmq.py   SQS queue         -> RabbitMQ     (drain with publisher confirms)
  04_dynamodb.md          DynamoDB guidance (data model change: no blind copy)
Every script is a dry run unless explicitly confirmed (CONFIRM=yes / --execute).
"""
from __future__ import annotations

import re
from pathlib import Path

PG_IMAGE = "postgres:16-alpine@sha256:1d5b02d3a9941fbd52437db4107f8c52d6297dac553ca1e5c299ebb3756b4857"
RCLONE_IMAGE = "rclone/rclone:1.70@sha256:34c729127386abec1c610b2aa024e39b4498dc2b4a72a0798ae21fbdc1b0493b"
DIR_NAME = "data-migration"

_BLOCK = re.compile(r'resource\s+"(aws_[\w]+)"\s+"[\w-]+"\s*\{(.*?)^\}', re.S | re.M)
_ATTR = r'^\s*{name}\s*=\s*"([^"]+)"'


def _attr(body: str, name: str) -> str | None:
    m = re.search(_ATTR.format(name=name), body, re.M)
    return m.group(1) if m else None


def infer_resources(target: Path) -> dict:
    """Best-effort names from Terraform / code / compose, used as script defaults."""
    res = {"bucket": None, "queue": None, "queue_url": None, "db_name": None, "db_user": None,
           "db_identifier": None, "region": None}
    target = Path(target)
    files = [target] if target.is_file() else [p for p in target.rglob("*") if p.is_file()
                                                and ".git" not in p.parts and ".venv" not in p.parts]
    for p in files:
        if p.suffix == ".tf":
            text = p.read_text(encoding="utf-8", errors="replace")
            res["region"] = res["region"] or _attr(text, "region")
            for kind, body in _BLOCK.findall(text):
                if kind == "aws_s3_bucket":
                    res["bucket"] = res["bucket"] or _attr(body, "bucket")
                elif kind.startswith("aws_sqs_queue"):
                    res["queue"] = res["queue"] or _attr(body, "name")
                elif kind in ("aws_db_instance", "aws_rds_cluster"):
                    res["db_name"] = res["db_name"] or _attr(body, "db_name") or _attr(body, "database_name")
                    res["db_user"] = res["db_user"] or _attr(body, "username") or _attr(body, "master_username")
                    res["db_identifier"] = res["db_identifier"] or _attr(body, "identifier")
        elif p.suffix in (".py", ".yml", ".yaml") and p.stat().st_size < 1_000_000:
            m = re.search(r"https://sqs\.([\w-]+)\.amazonaws\.com/\d+/[\w.-]+", p.read_text(errors="replace"))
            if m and not res["queue_url"]:
                res["queue_url"], res["region"] = m.group(0), res["region"] or m.group(1)
    return res


