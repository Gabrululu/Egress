"""LLM code changes as COMPLETE files -> exact git-style diffs + verification.

LLMs are unreliable at writing unified diffs (wrong hunk counts, missing a/ b/ prefixes,
overlapping hunks). So the LLM returns whole migrated files and Egress computes the diffs
itself with difflib: the diff is always well-formed and always applies. What remains to check
is the *code*, which `code_problem` does by building the patched repo for real.
"""
from __future__ import annotations

import re
import tempfile
from pathlib import Path, PurePosixPath

from .apply import RETIRE, STACK_LEVEL, _matches, build_app_from_source
from .fallback import _git_diff

MAX_FILES = 12
# Generated by Egress itself (with the random credentials) or secret: never taken from the LLM.
EGRESS_MANAGED = ("seaweedfs/", "data-migration/")
SECRET_FILES = (".env", ".env.*", "*.pem", "*.key")
MAX_FILE_BYTES = 60_000
# Placeholders that mean the model elided code instead of writing the full file.
_ELISION = re.compile(r"^\s*(?:#|//)\s*(?:\.\.\.|…)\s*$|^\s*(?:#|//)\s*\.*\s*(?:rest of (?:the )?(?:code|file)|"
                      r"(?:existing|unchanged|same) (?:code|logic|implementation)|code unchanged)", re.I | re.M)
# Env vars the generated compose provides; the migrated code must actually read them.
REQUIRED_ENV = {
    "app.py": ("S3_ENDPOINT_URL", "AMQP_URL", "QUEUE_NAME", "DB_HOST"),
    "worker.py": ("AMQP_URL", "QUEUE_NAME"),
}


def _safe_path(p: str) -> str | None:
    """Repo-relative POSIX path, or None if absolute / escaping / hidden-git."""
    if not isinstance(p, str) or not p.strip() or "\\" in p or "\x00" in p:
        return None
    pp = PurePosixPath(p.strip().removeprefix("./"))
    if pp.is_absolute() or ".." in pp.parts or not pp.parts or pp.parts[0] == ".git":
        return None
    return str(pp)


def files_to_diffs(files, target: Path) -> tuple[list[dict] | None, list[str]]:
    """Validate the LLM `files` list and turn it into exact git-style diffs.

    Returns (diffs or None, problems). Stack-level (compose) and retired (Terraform) files are
    ignored: the stack comes from the validated docker_compose part."""
    problems: list[str] = []
    if not isinstance(files, list) or not files:
        return None, ["no files returned"]
    base = target if target.is_dir() else target.parent
    diffs, seen = [], set()
    for entry in files[:MAX_FILES]:
        if not isinstance(entry, dict):
            continue
        path = _safe_path(entry.get("path", ""))
        content = entry.get("content")
        original = (entry.get("original") or "").strip()
        if path is None:
            problems.append(f"unsafe or empty path {entry.get('path')!r}")
            continue
        # The compose builds ./app from the repo root, so models often write "app/app.py".
        if path.startswith("app/") and not (base / "app").is_dir():
            path = path.removeprefix("app/")
        if _matches(PurePosixPath(path).name, RETIRE + STACK_LEVEL + SECRET_FILES) or path in seen \
                or path.startswith(EGRESS_MANAGED):
            continue
        seen.add(path)
        if not isinstance(content, str) or not content.strip():
            problems.append(f"{path}: empty content")
            continue
        if len(content.encode("utf-8")) > MAX_FILE_BYTES:
            problems.append(f"{path}: file too large")
            continue
        if _ELISION.search(content):
            problems.append(f"{path}: contains an elision placeholder ('...'); return the complete file")
            continue
        orig = _safe_path(original) if original else None
        if original and orig is None:
            problems.append(f"{path}: unsafe original path {original!r}")
            continue
        if orig is None and (base / path).is_file():
            orig = path  # model forgot `original` for an existing file: treat as modification
        if orig is not None and not (base / orig).is_file():
            orig = None  # original does not exist: new file
        new_lines = (content if content.endswith("\n") else content + "\n").splitlines(keepends=True)
        old_lines = (base / orig).read_text(encoding="utf-8", errors="replace").splitlines(keepends=True) \
            if orig else []
        d = _git_diff(orig, path, old_lines, new_lines)
        if d:
            diffs.append({"file": path, "diff": d})
    if not diffs and not problems:
        problems.append("files produced no changes")
    return (diffs or None), problems


def code_problem(diffs: list[dict], target: Path) -> str | None:
    """Build the patched repo in a scratch dir and run every gate. Returns a problem or None."""
    from scanner import scan

    with tempfile.TemporaryDirectory(prefix="egress-code-") as tmp:
        dest = Path(tmp) / "app"
        res = build_app_from_source(target, diffs, dest)
        if res["app_source"] != "patched-repo":
            failed = [f"{p['file']}: {p['detail']}" for p in res["patches"] if p["status"] == "failed"]
            return "; ".join([res["reason"], *failed, *res["problems"]])[:1500]
        problems = []
        for name, names in REQUIRED_ENV.items():
            text = (dest / name).read_text(encoding="utf-8", errors="replace")
            missing = [n for n in names if n not in text]
            if missing:
                problems.append(f"{name} does not read env vars {missing}")
        report = scan(dest)
        left = [f for f in report["findings"] if not f.get("mitigated")]
        problems += [f"remaining AWS lock-in: {f['file']}:{f['line']} {f['service']} `{f['evidence'][:80]}`"
                     for f in left[:8]]
        return "; ".join(problems)[:1500] or None
